# The regex should match each language block and inject the new keys before the closing brace of the language object
for lang, keys_content in new_keys.items():
    # Find the language block
    pattern = r"('" + lang + r"'|(?<!')\b" + lang + r"\b)\s*:\s*\{([^}]*)\}"
    
    def repl(match):
        lang_key = match.group(1)
        inner_content = match.group(2)
        # Ensure trailing comma on the last item if it doesn't have one
        if not inner_content.strip().endswith(','):
            inner_content += ','
        return f"{lang_key}: {{{inner_content}\n{keys_content}}}"

    content = re.sub(pattern, repl, content)

with open('src/translations.ts', 'w', encoding='utf-8') as f:
    f.write(content)
